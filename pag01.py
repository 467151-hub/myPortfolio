print("เลือกชนิดรูปทรง")
print("1. สี่เหลี่ยมจัตุรัส")
print("2. สี่เหลี่ยมผืนผ้า")

เลือก = input("กรุณาเลือก (1 หรือ 2): ")

if เลือก == "1":
    ด้าน = float(input("กรอกความยาวด้าน: "))
    พื้นที่ = ด้าน * ด้าน
    print("พื้นที่สี่เหลี่ยมจัตุรัสคือ", พื้นที่)

elif เลือก == "2":
    กว้าง = float(input("กรอกความกว้าง: "))
    ยาว = float(input("กรอกความยาว: "))
    พื้นที่ = กว้าง * ยาว
    print("พื้นที่สี่เหลี่ยมผืนผ้าคือ", พื้นที่)

else:
    print("กรุณาเลือกให้ถูกต้อง (1 หรือ 2)")
