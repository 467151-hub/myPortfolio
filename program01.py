# โปรแกรมคำนวณพื้นที่และเส้นรอบรูปสี่เหลี่ยมผืนผ้า

กว้าง = float(input("กรอกความกว้าง: "))
ยาว = float(input("กรอกความยาว: "))

if กว้าง > 0 and ยาว > 0:
    พื้นที่ = กว้าง * ยาว
    เส้นรอบรูป = 2 * (กว้าง + ยาว)

    print("\nผลการคำนวณ")
    print("ความกว้าง =", กว้าง)
    print("ความยาว =", ยาว)
    print("พื้นที่ =", พื้นที่)
    print("เส้นรอบรูป =", เส้นรอบรูป)
else:
    print("กรุณากรอกค่ามากกว่า 0")
